export function typeMultiplier(attack: string, defense: string): number {
  if (!TYPE_INDEX.has(attack) || !TYPE_INDEX.has(defense)) return 1
  return CHART[attack]?.[defense] ?? 1
}

export function effectiveness(attack: string, types: string[], ability: string): number {
  let value = types.reduce((total, defense) => total * typeMultiplier(attack, defense), 1)
  if (ability === "ふゆう" && attack === "じめん") value = 0
  if (ability === "ひらいしん" && attack === "でんき") value = 0
  if ((ability === "ちょすい" || ability === "よびみず" || ability === "かんそうはだ") && attack === "みず") value = 0
  if (ability === "もらいび" && attack === "ほのお") value = 0
  if (ability === "そうしょく" && attack === "くさ") value = 0
  if (ability === "かんそうはだ" && attack === "ほのお") value *= 1.25
  if (ability === "あついしぼう" && (attack === "ほのお" || attack === "こおり")) value *= 0.5
  if (ability === "たいねつ" && attack === "ほのお") value *= 0.5
  if (ability === "もふもふ" && attack === "ほのお") value *= 2
  if ((ability === "フィルター" || ability === "ハードロック" || ability === "プリズムアーマー") && value > 1) value *= 0.75
  return value
}

export interface Weakness {
  type: string
  value: number
}

export function weaknesses(types: string[], ability: string): Weakness[] {
  return TYPES.flatMap((attack) => {
    const value = effectiveness(attack, types, ability)
    return value > 1 ? [{ type: attack, value }] : []
  })
}

