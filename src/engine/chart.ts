export function natureNames(): string[] {
  return Object.keys(NATURES)
}

export function hasNature(name: string): boolean {
  return name === "まじめ" || name in NATURES
}

function natureFactor(nature: string, stat: StatKey): number {
  const found = NATURES[nature]
  if (!found || stat === "H") return 1
  if (found.up === stat) return 1.1
  if (found.down === stat) return 0.9
  return 1
}

export function calcStat(base: number, points: number, nature: string, stat: StatKey): number {
  const inner = Math.floor(((2 * base + 31) * 50) / 100)
  if (stat === "H") return inner + 60 + points
  return Math.floor((inner + 5 + points) * natureFactor(nature, stat))
}

