function splitField(value: string): string[] {
  if (!value || value === "-") return []
  return value.split("/").map((part) => part.trim()).filter(Boolean)
}

function parseLine(line: string, lineNo: number): SetData | null {
  const parts = line.split("|")
  if (parts.length !== 14) {
    console.warn(`型データの列数が違います (${lineNo}): ${line.slice(0, 40)}`)
    return null
  }
  const [name, themeText, offense, ability, itemText, nature, pointText, moveText, role, intent, answerText, loseText, partnerText, coreText] = parts
  if (!name || (offense !== "physical" && offense !== "special")) return null
  const themes = splitField(themeText).filter((theme): theme is Theme => THEMES.includes(theme as Theme))
  const points = pointText.split(",").map((value) => Number(value))
  const moves = splitField(moveText)
  if (points.length !== 6 || moves.length < 1 || moves.length > 4) return null
  return {
    name,
    themes,
    offense,
    ability,
    items: splitField(itemText),
    nature,
    points: points as SetData["points"],
    moves,
    role,
    intent,
    answers: splitField(answerText),
    losesTo: splitField(loseText),
    partners: splitField(partnerText),
    core: coreText === "1",
    estimated: false,
  }
}

let cache: SetData[] | null = null

export function allSets(): SetData[] {
  if (cache) return cache
  cache = RAW.split(/\r?\n/)
    .map((line, index) => ({ line: line.trim(), index }))
    .filter((entry) => entry.line && !entry.line.startsWith("#"))
    .map((entry) => parseLine(entry.line, entry.index + 1))
    .filter((set): set is SetData => set !== null)
  return cache
}

export function setsFor(name: string): SetData[] {
  return allSets().filter((set) => set.name === name)
}

export function validateSets(): string[] {
  const problems: string[] = []
  for (const set of allSets()) {
    const mon = findMon(set.name)
    if (!mon) {
      problems.push(`図鑑にいない: ${set.name}`)
      continue
    }
    if (!mon.abilities.includes(set.ability)) problems.push(`${set.name} の特性が一覧にない: ${set.ability}`)
    if (!hasNature(set.nature)) problems.push(`${set.name} の性格が不明: ${set.nature}`)
    const sum = set.points.reduce((total, value) => total + value, 0)
    if (sum !== 66 || set.points.some((value) => value < 0 || value > 32)) {
      problems.push(`${set.name} の努力値が66/32を外れている: ${set.points.join(",")}`)
    }
    for (const item of set.items) {
      if (!hasItem(item)) problems.push(`${set.name} の持ち物が一覧にない: ${item}`)
    }
    if (set.name.startsWith("メガ")) {
      const stone = MEGA_STONES[set.name]
      if (!stone) problems.push(`メガストーン未対応: ${set.name}`)
      else if (!set.items.includes(stone)) problems.push(`${set.name} が ${stone} を持っていない`)
    }
    for (const move of set.moves) {
      if (move !== "まもる" && move !== "ウェザーボール" && !moveType(move, set.ability) && !STATUS.has(move)) {
        problems.push(`${set.name} の技が未登録: ${move}`)
      }
    }
  }
  return problems
}

